# Regenerates THIRD_PARTY_LICENSES.txt: full license text (and NOTICE files) of
# every Go module compiled into the server binary, plus the Go standard library.
# Run from the repository root after changing dependencies:
#   go mod download && bash scripts/third-party-licenses.sh
set -euo pipefail

out=THIRD_PARTY_LICENSES.txt
gmc=$(go env GOMODCACHE)
goroot=$(go env GOROOT)

{
  echo "Third-party licenses for Storyboard Studio"
  echo "Generated by scripts/third-party-licenses.sh from the modules compiled into ./cmd/server."
  echo "Runtime tools that are NOT compiled in (ffmpeg, PostgreSQL) are listed in THIRD_PARTY_NOTICES.md."
  echo
  echo "================================================================================"
  echo "Go standard library ($(go env GOVERSION)) - BSD-3-Clause"
  echo "================================================================================"
  cat "$goroot/LICENSE"
  echo

  go list -deps -f '{{if .Module}}{{.Module.Path}}@{{.Module.Version}}{{end}}' ./cmd/server |
    sort -u | grep -v '^storyboard' | while read -r m; do
      path=${m%@*}; ver=${m#*@}
      # Module cache escapes upper-case letters as "!" + lower-case.
      esc=$(printf '%s' "$path" | sed -E 's/([A-Z])/!\L\1/g')
      dir="$gmc/$esc@$ver"
      echo "================================================================================"
      echo "$path $ver"
      echo "================================================================================"
      found=0
      for f in "$dir"/LICENSE* "$dir"/LICENCE* "$dir"/COPYING* "$dir"/NOTICE*; do
        [ -f "$f" ] || continue
        found=1
        echo "--- $(basename "$f") ---"
        cat "$f"
        echo
      done
      if [ "$found" = 0 ]; then
        echo "ERROR: no license file found in $dir" >&2
        exit 1
      fi
    done
} > "$out"

echo "wrote $out"
